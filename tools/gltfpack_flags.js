// pack_glb.js と unpack_glb.js で使う gltfpack のフラグ。1 か所に置くのは、
// 2 本がずれると「戻して詰め直す」往復のたびに型のキーが間引かれたり位置が
// 量子化されたりするから。どちらか片方だけ直す事故を防ぐ。
//
// -kn/-km/-ke: 名前付きの節点・素材・extras を落とさない。
// -vpf: 位置は float のまま (量子化しない)。当たりの元になる形が丸まらない。
// -vt 16: UV は 16 ビット。
// -af 0: アニメーションをリサンプルしない (既定は 30Hz で、型のキーが
//   間引かれる)。兵士は動きそのものが中身なので、キーは元のまま残す。
//   ** -cc が無いときもこの指定は要る ** — gltfpack は圧縮しなくても
//   既定の加工 (30Hz リサンプルと位置の量子化) を掛ける。
export const GLTFPACK_FLAGS = ['-kn', '-km', '-ke', '-vpf', '-vt', '16', '-af', '0']
