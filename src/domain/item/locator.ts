/**
 * E LOCATOR。**倒す道具ではなく、場所を暴く道具。**
 *
 * --- なぜ要るか ---
 * いま在る支援は 3 つとも「相手に何かをさせる」物で、**自分から情報を取りに
 * 行く**物が無い:
 *
 *     GRENADE   相手を動かす  → 止まっている相手
 *     CLAYMORE  置いて待つ    → 動いている相手
 *     DECOY     撃たせる      → 見ている相手
 *     LOCATOR   居場所を暴く  → **隠れている相手**
 *
 * この遊びの核は情報で、接敵までは互いに透明でいようとする。透明でいる側を
 * 剥がす手が無いと、隠れ続けるのが常に得になる。
 *
 * --- なぜ投げる物か ---
 * 置く物 (クレイモア / decoy) は自分の足元にしか置けない。暴きたいのは
 * **自分が行けない場所**なので、届かせる手段が要る。手榴弾と同じ弧で放れば、
 * 「そこへ落とす」判断がそのまま「そこを覗く」判断になる。
 *
 * --- なぜ見えて、壊せるか ---
 * 壊せないと、投げた側が一方的に情報を得るだけで読み合いが生まれない。
 * 見えて壊せるなら、両側に手が残る:
 *
 *     投げた側  見えない所へ投げたい  (壊されないため)
 *     暴かれた側  探して壊したい      (光り続けないため)
 *
 * **点滅はそのための手掛かり。** 静かに置いてあるだけだと、暴かれた側は
 * 「どこかに在る」ことしか分からず、探しようがない。光れば見つけられる —
 * 代わりに、投げた側は光る物を隠せる場所を選ぶことになる。
 */

/**
 * 暴く半径 (m)。**壁は見ない。**
 *
 * 見通しを要るようにすると、置いた瞬間に仕事が終わっている (見えている相手は
 * 既に見えている)。壁を抜けるからこそ、部屋の中や階の上を覗く道具になる。
 *
 * 15m は「1 区画ぶん」。筏 (砂部屋) は見通しが長いので、ここを広げると
 * 投げた側が寝ていても地図の半分が見える道具になる。
 */
export const SCAN_RADIUS = 15

/**
 * 着いてから消えるまで (秒)。**飛んでいる間は減らない。**
 *
 * 投げ損なって遠くへ転がった分まで寿命を食うと、「置き場所を選ぶ」ことが
 * 運になる。止まった所から数え始める。
 */
export const LIFE_SECONDS = 20

/**
 * 何秒ごとに周りを見るか。
 *
 * 毎刻み (64Hz) 見ても結果は変わらないのに、晒し直す通だけが増える。
 * 1 秒は「歩いて半径を出入りする」より細かいので、抜け落ちない。
 */
export const SCAN_SECONDS = 1

/**
 * 1 回の走査で残る気配の長さ (秒)。**走査の間隔より長くする。**
 *
 * 同じ長さにすると、次の走査が届く前に消えて**明滅する**。少し長くしておけば
 * 半径の中に居る間は気配が続き、出た後に少しだけ残る — その残りが
 * 「さっきまでそこに居た」という情報になる。
 *
 * --- 輪郭ではなく気配 ---
 * 長らく相手を光らせていた (ENEMY EXPOSURE と同じ輪郭)。輪郭だと向きも姿勢も
 * 読めて、壁越しに**撃つ準備**まで済んでしまう。この道具の仕事は「どの辺に
 * 居るか」を覗くことなので、AWARENESS と同じ霧に留める。位置は走査の瞬間の
 * 物で、次の走査まで動かない — 1 秒前の居場所、という粗さがそのまま代償。
 */
export const SENSE_SECONDS = 2

/**
 * 撃たれたときの当たり (m)。中心から左右前後にこれだけと、地面からの高さ。
 *
 * **模型に合わせてある** (public/models/locator.glb は幅 0.12m・高さ 0.23m)。
 * 見えている形と当たる形が食い違うと、**狙って当てたのに壊れない**が起きる。
 * 模型を作り直したら、ここも測り直す。
 *
 * 少しだけ細くしてある。同じ太さにすると縁を掠めた弾まで当たって、
 * 「狙っていないのに壊れる」になる。
 */
export const SHOT_HALF = 0.05
export const SHOT_TOP = 0.23

/**
 * 点滅の間隔 (秒)。**1 秒に 1 回光る。**
 *
 * 走査の間隔と揃える。光った瞬間に周りを見ている、という形にしておくと、
 * 見つけた側が「いま自分が暴かれた」と読める。速く点滅させると、ただの
 * 目印になって「いつ暴かれたか」が消える。
 */
export const BLINK_SECONDS = SCAN_SECONDS

/** 光っている長さ (秒)。点滅の中で灯っている側 */
export const BLINK_ON = 0.12
