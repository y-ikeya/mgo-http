/**
 * 囮の人形。**撃つことに代償を付ける道具。**
 *
 * --- なぜ要るか ---
 * いま在る支援は「相手を動かす」(手榴弾) と「置いて待つ」(クレイモア) の 2 つで、
 * **撃つという行為そのものに代償を付ける物が無い**。この遊びの核は情報で、
 * 接敵までは互いに透明でいようとする — その形に一番強く効くのがこれ。
 *
 *     GRENADE   相手を動かす  → 止まっている相手
 *     CLAYMORE  置いて待つ    → 動いている相手
 *     DECOY     撃たせる      → **見ている相手**
 *
 * --- なぜ人形でなければならないか ---
 * 撃たれて初めて効くので、**撃ちたくなる形をしていないと置いても何も起きない。**
 * 音だけで釣る (弾倉の囮) より作るのは重いが、視界の端で人に見えないと
 * 一瞬の判断で撃たせられない。
 *
 * 同時に**よく見れば分かる**ことも要る。分からないと「撃つのが常に損」になって
 * 撃ち合いそのものが止まる。平たい台がその手掛かりで、**落ち着いて見る余裕が
 * あった側だけが騙されない** — 余裕の有無が結果を分けるので読み合いになる。
 */

/**
 * 置いてから膨らみ切るまで (秒)。
 *
 * **膨らんでいる間そのものが情報になる。** 半分の大きさの人形は誰が見ても
 * 偽物なので、**見られたら罠が死ぬ**。「相手の目の前には置けない」が
 * ここから自然に出る — 距離や数の規則を足さずに済む。
 */
export const DEPLOY_SECONDS = 2

/**
 * 撃った相手が光っている長さ (秒)。
 *
 * スキル (ENEMY EXPOSURE) と同じ長さ。**当てた相手が光る**のと
 * **囮を撃った相手が光る**のは、遊びの中では同じ意味の情報なので揃える。
 */
export const EXPOSE_SECONDS = 5

/**
 * 撃たれたときの当たり (m)。中心から左右前後にこれだけ、と高さ。
 *
 * **人より少しだけ細い。** 同じ太さにすると、人形の縁を掠めた弾まで割れて
 * 「狙っていないのに罠に掛かる」になる。狙って撃った弾だけが割る。
 */
export const SHOT_HALF = 0.3
export const SHOT_TOP = 1.7

/**
 * 置ける場所の前方向 (m)。クレイモアと同じ。
 *
 * 足元ではなく少し前に置く。足元だと自分の体と重なって、置いた本人から
 * 見えなくなる。
 */
export const PLACE_FORWARD = 0.9

/**
 * ぶつかったと見なす近さ (m)。人の半径 + 人形の半分。
 *
 * **人は止めない。** 風船なので通り抜けられる — 止めると盾になって、
 * 「撃たせる道具」が「隠れる道具」に変わる。代わりに押しのけられて揺れる。
 *
 * 揺れは**見えている全員に届く**ので、離れた所から自分の囮が揺れるのが
 * 見えたら「誰かがそこを通った」と読める。撃たせる道具であると同時に、
 * **見張る道具**でもある。
 */
export const BUMP_RANGE = 0.65

/**
 * 同じ人形が続けて揺れないようにする間 (秒)。
 *
 * 傍に立ち続けている人が居ると毎刻み揺れて、**そこに誰か居ることが
 * 揺れっぱなしで漏れる**。1 度揺れたらしばらく静かにする — 通った
 * ことは伝わるが、留まっていることまでは伝わらない。
 */
export const BUMP_COOLDOWN = 1.5
