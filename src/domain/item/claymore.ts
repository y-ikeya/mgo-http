/**
 * クレイモア。置いて、前を通った敵で起爆する。
 *
 * --- 手榴弾と何が違うか ---
 * 手榴弾は「相手を動かす」道具で、投げた本人が結果を見る。クレイモアは
 * **置いて離れる**道具で、置いた場所に相手が来るかどうかは相手が決める。
 * 「そこは通らせない」を作る物なので、当たるかどうかより**通り道を潰す**ことに
 * 意味がある。
 *
 * --- なぜ向きがあるか ---
 * 見張るのは前だけ。全方位なら「置いた場所が危ない」だけで済むが、向きがあると
 * 「どちらから来ると危ないか」になる。置く側は通り道を読んで向きを決め、
 * 通る側は背後から回れば無事。**読み合いが 1 段増える。**
 *
 * **爆ぜてからは全方位。** 向きが意味を持つのは「いつ起爆するか」まで。
 * 火薬に前も後ろも無い — 真後ろに立っていた人だけ無傷、は物として嘘になる。
 *
 * 置ける場所かどうか (埋まる / 浮く) の判定は世界に訊く話なので
 * sim/judge/claymore.ts。
 */

/** 反応する距離 (m)。これより遠い敵には反応しない */
export const TRIGGER_RANGE = 4

/**
 * 反応する角度。正面から左右 60 度まで。
 *
 * 広げると「置いた場所が危ない」に近づき、狭めると避けやすくなりすぎる。
 * 正面 120 度は、通路を塞ぐには足りて、横を抜けるには広すぎない辺り。
 */
export const TRIGGER_ANGLE = 60
export const TRIGGER_COS = Math.cos((TRIGGER_ANGLE * Math.PI) / 180)

/** 爆風が届く距離 (m)。反応する距離より少し広い — 反応した時点で逃げ切れない */
export const BLAST_RANGE = 6

/**
 * 至近で与える量。
 *
 * **単体では死なない** (体力 100 に対して 75)。手榴弾の爆風と同じ考え方で、
 * 置いただけで一発というのは強すぎる — 踏んだ相手は瀕死で逃げるか、
 * 追撃されて死ぬ。**置いた側がその場に居るかどうか**が結果を分ける。
 *
 * 置いた本人も巻き込まれる。自分で踏むと 75 削れる。満身なら死なないが、
 * 撃ち合いのあとに戻ってきて踏むと死ぬ。
 */
export const BLAST_MAX = 75

/** 端で与える量。掠めれば死なない */
export const BLAST_MIN = 25

/**
 * 転ぶ距離。届く距離に対する割合。
 *
 * 手榴弾は 7m のうち 5m で転ぶ ([grenade.ts](grenade.ts) の KNOCK_NEAR) ので、
 * それに揃える。道具ごとに別の勘で決めると、受けた側が「どこまで下がれば
 * 立っていられるか」を覚え直すことになる。
 */
export const KNOCK_RATIO = 0.72

/** 爆風を受けた結果。手榴弾と同じ形 (item/grenade.ts) */
export interface BlastEffect {
  damage: number
  knock: boolean
}

/**
 * その距離で、どれだけ削れて転ぶか。
 *
 * 至近で 75、端で 25 まで線形に落ちる。**置いた本人も例外にしない** — 誰に
 * 当たったかを見ないのは、自分の物で削れることを規則として認めているため。
 *
 * 距離を測るのは sim (judge/claymore.ts の blastReach)。
 */
export function blastEffect(distance: number): BlastEffect {
  if (distance > BLAST_RANGE) return { damage: 0, knock: false }
  const t = distance / BLAST_RANGE
  return {
    damage: BLAST_MAX - t * (BLAST_MAX - BLAST_MIN),
    // 手榴弾と同じ割合 (届く距離の 7 割) で転ぶ。端で掠っただけの相手は立っている
    knock: t < KNOCK_RATIO,
  }
}
