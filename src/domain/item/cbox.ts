/**
 * 誰も入っていないダンボール (ステージの置き物)。
 *
 * --- 何のためか ---
 * 被る箱 (CBOX MOVE) は、見た目で人が入っているか分からないのが肝。空の箱が
 * 転がっていて初めて「疑う」意味が出る。同じ絵・同じ寸法で置く。
 *
 * --- 触れると揺れる ---
 * decoy と同じで、**触った事実は審判が見つけて全員に配る** (申告は受けない)。
 * 離れた所から揺れるのが見えれば「誰かがそこを通った」と読める。揺れるのは
 * 1 回だけ (ガタッ)。人形のようにぷるぷる続けない — 紙箱は押されたぶん動いて
 * 止まる物で、続けて揺れると生き物に見える。
 *
 * 寸法は被る箱 (presentation/scene/actor/box.ts の tuning) と同じ。書き出し
 * (tools/export_stage.py の CBOX_*) も同じ値を持つ。
 */

/** 横 / 高さ / 奥行 (m) */
export const CBOX_WIDTH = 0.9
export const CBOX_HEIGHT = 1.0
export const CBOX_DEPTH = 1.2

/**
 * 触れたと見なす隙間 (m)。箱の面から体の中心までが半径 (0.35) + これ以内。
 *
 * 人は箱に止まる (当たりがある) ので、押している間は面から 0.35m の所に居る。
 * 少し余裕を持たせて、歩きながら掠めた時も拾う
 */
export const BUMP_SLACK = 0.12

/** 揺れてから次に揺れるまで (秒)。押し続けても連打にならない */
export const BUMP_COOLDOWN = 1.2

/** 揺れが収まるまで (秒)。1 往復半で止まる */
export const BUMP_SETTLE = 0.45
