/**
 * 遅れをどちらに味方させるか。
 *
 * --- なぜこれが遊びのドメインルールなのか ---
 * 撃った人の画面と、サーバーが知っている世界は同じではない。回線の往復と
 * 補間の遅れのぶん、**撃った瞬間に見えていた相手はもうそこに居ない。**
 * どちらの言い分を採るかを決めないと当たり判定が成立しない。
 *
 *     当てた側に寄せる   「画面で当たっていたのに通らない」が減る
 *     避けた側に寄せる   「壁に隠れたのに撃たれた」が減る
 *
 * **両方は満たせない。** ここにあるのはその配分で、動かせば撃ち合いの手触りが
 * 変わる — だから幾何 (sim) ではなくドメインルール (domain) に置く。
 *
 * MGO2 の遊びは「接敵したら撃ち合い、動かない側が有利」なので、**撃った側に
 * 寄せる**。動いて避けた側の言い分を採ると、止まって撃つ側が損をする。
 *
 * 実際に何個ぶん記録するか (履歴の長さ) は送る間隔から出る実装の値なので、
 * サーバー側に置いてある。
 */

/**
 * 遡れる長さ (ms)。
 *
 * 通信の往復 + 補間の遅れ (0.1 秒) を覆える幅にする。広く取るほど当てた側の
 * 体感は正しくなり、避けた側は「隠れたのに撃たれた」が増える。
 */
export const LAG_WINDOW_MS = 400

/**
 * ここを超えると**弾が通らなくなる**往復の時間 (ms)。
 *
 * --- なぜ遡れる長さから出るのか ---
 * サーバーが遡るのは「撃った人の画面に映っていた瞬間」まで。その瞬間は
 * **2 つぶん過去**にある。
 *
 *     補間の遅れ    相手を何秒過去で描いているか (最大 0.25 秒)
 *     片道          撃った申告がサーバーへ着くまで (往復の半分)
 *
 * 足したものが遡れる長さ (LAG_WINDOW_MS) を超えると、**照合の窓から外れて
 * 却下される** — 画面では当てているのに何も起きない。
 *
 *     遡る必要 = 補間の遅れ + 往復 / 2 ≦ 400ms
 *     往復     ≦ (400 − 250) × 2 = 300ms
 *
 * **窓を広げれば緩むが、その代金は全員が払う** — 遡るほど「壁に隠れたのに
 * 撃たれた」が増える。遅い人 1 人のために全員の手触りを変えない。
 *
 * 補間の上限 (0.25 秒) は sim の値なので、ここからは読めない (層が逆)。
 * **食い違ったら試験が落ちる** — lag.test.ts で突き合わせてある。
 */
export const HIT_LIMIT_MS = 300

/**
 * 距離の申告に許す誤差。
 *
 * 撃った瞬間と、サーバーが知っている位置には時間差がある。相手が走っていれば
 * その間に動く。固定値だけだと遠射で足りず、比率だけだと至近で足りない。
 *
 *     許す誤差 = DISTANCE_SLACK + 距離 × DISTANCE_SLACK_RATE
 */
export const DISTANCE_SLACK = 3
export const DISTANCE_SLACK_RATE = 0.06

/** ナイフの間合いに許す余裕 (m)。踏み込みと時間差のぶん */
export const MELEE_SLACK = 1.2
