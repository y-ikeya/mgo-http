/**
 * 遅れの限界。**待てなくなった人には席を空けてもらう。**
 *
 * --- なぜ規則なのか ---
 * 遅れは「その人の回線が悪い」で終わる話ではない。**遅れている人が居ると、
 * 他の全員の画面が壊れる。**
 *
 *     その人の姿が飛ぶ・明滅する         (位置が飛び飛びにしか届かない)
 *     撃っても当たらない・当たっていない  (照合の窓は 0.4 秒しか遡れない)
 *     こちらの弾は当たったことにされる    (向こうの画面では既に動いている)
 *
 * 撃ち合いが読み合いとして成立しなくなるので、**部屋の側の問題**として扱う。
 *
 * --- なぜ即座に切らないか ---
 * 往復の時間は跳ねる。電波が一瞬途切れただけで 1 秒を超えるのは普通にある。
 * 1 回で切ると、繋ぎ直しては切られるを繰り返す人が出る。**続いたときだけ**
 * 切る。
 */

/** これを超えたら遅れていると見なす (ms) */
export const LAG_LIMIT_MS = 999

/**
 * 何回続いたら席を空けてもらうか。
 *
 * 1 秒に 1 回測るので 5 秒ぶん。**一瞬の跳ねでは切らず、直らないなら切る。**
 */
export const LAG_STRIKES = 5

/**
 * 遅れの控え。**回数だけを持つ。**
 *
 * 直近の値ではなく続いた回数で決めるので、持つのはこれで足りる。
 */
export interface LagRecord {
  /** 均した往復の時間 (ms)。0 ならまだ測れていない */
  rtt: number
  /** 続けて限界を超えた回数 */
  strikes: number
}

export function newLagRecord(): LagRecord {
  return { rtt: 0, strikes: 0 }
}

/**
 * 往復の時間を 1 つ受ける。**席を空けてもらうなら true。**
 *
 * 均すのは表示のため。**切る判断は均す前の値で見る** — 均すと、跳ねが
 * 混ざって「超えているのに超えていないことになる」時間が伸びる。
 */
export function recordLag(record: LagRecord, rtt: number): boolean {
  // 出たばかりは均す相手が居ない。最初の値をそのまま置く
  record.rtt = record.rtt === 0 ? rtt : record.rtt + (rtt - record.rtt) * 0.3
  record.strikes = rtt >= LAG_LIMIT_MS ? record.strikes + 1 : 0
  return record.strikes >= LAG_STRIKES
}
