/**
 * その人が**何をしようとしているか**。
 *
 * --- なぜ domain なのか ---
 * 動詞の一覧は遊びの定義そのもの (docs/design.md の 4)。「敬礼できる」
 * 「スキャンできる」を足すのは遊びが変わることで、`KeyG` を `KeyH` に
 * 変えるのは変わらない。**動詞はここ、キーの割り当ては presentation。**
 *
 * いずれサーバーへ送ることになる (design.md の TO-BE「入力を受けてサーバーが
 * 動かす」)。そのとき線に載るのがこれなので、`Pose` と同じく共有の語彙にしておく。
 *
 * --- 何を入れないか ---
 * **押されているかだけを入れる。**
 *
 *     入れる    aim (押している)
 *     入れない  実際に構えているか (受け付けた結果。機械が持つ)
 *               時間の経過 (dt は別に渡す)
 *               クリップの尺のような描画側の事実 (ctx として別に渡す)
 *
 * 混ぜると、ここが「Game.ts のフィールド置き場」になる。構えは特に紛らわしい —
 * 箱を被っていたり敬礼中は押しても構えないので、**押していること**と
 * **構えていること**は別物 (presentation/scene/actor/player.ts の isAiming)。
 *
 * --- まだ全部は無い ---
 * Game.ts から順に掘り出している途中で、いまあるのは手にある物まわりだけ。
 * 撃つ・投げる・置く・刺すは、その機械を出すときに足す。
 */

import type { Family } from '../item/held'

export interface Intent {
  /**
   * 系統ごとの「送りのキーを押しているか」。
   *
   * **押した長さで意味が変わる** — 短ければトグル、長押しなら一覧が開く。
   * だから立ち上がりではなく、押しているかどうかを渡す。
   */
  browse: Record<Family, boolean>
  /**
   * 一覧の中を送る量。ホイールと右スティックのどちらでも同じだけ。
   *
   * 一覧を開いていないときは使われない。**使わなかったことは呼ぶ側に返す** —
   * 同じホイールをスコープの倍率も見ているので、取り合いになる。
   */
  select: number
  /** 置く / 拾う。一覧を開いていれば置く、開いていなければ拾う */
  drop: boolean
  /** 名指しで支援装備へ。一覧を開かずに行き先が決まっているとき */
  toSupport: boolean
}

/** 何も押していない。試験と、入力を受け付けない場面で使う */
export const NO_INTENT: Intent = {
  browse: { weapon: false, tool: false },
  select: 0,
  drop: false,
  toSupport: false,
}
