/**
 * 体がいまどの動きの中に居るか。
 *
 * --- なぜ src/game から出したか ---
 * ここは**共有の層**。サーバーも、位置の符号化も、足音も、姿勢のドメインルールも
 * この型を読む。にもかかわらず src/presentation/scene/actor/animation.ts (three を読み込む)
 * に置いてあったので、three に依存しないはずの src/sim と src/application/protocol が
 * **型の上では three へ繋がっていた**。
 *
 * 動いてはいた (bun は型を剥がすだけなので) が、サーバー側を型検査に
 * 入れようとした途端に表に出る。判定の層が描画の層を参照している、
 * という向きそのものが逆だった。
 *
 * クリップ名との対応 (どの .fbx を流すか) は描画の話なので animation.ts に残る。
 * ここに置くのは「どの状態があるか」だけ。
 */

/** 移動の 8 方向。前を 0 として時計回り */
export const MOVE_DIRECTIONS = ['f', 'fr', 'r', 'br', 'b', 'bl', 'l', 'fl'] as const
export type MoveDirection = (typeof MOVE_DIRECTIONS)[number]

/** 下半身レイヤーの状態 = 移動アニメ */
export type Locomotion =
  | 'idle'
  | 'crouch_idle'
  // ダンボールを被っている姿勢。全身クリップなので上下を分けない
  | 'sneak'
  | 'sit'
  | 'stab'
  /**
   * しゃがんだまま刺す。
   *
   * **下半身はしゃがみのまま、上半身だけが刺す型になる。** 立ちの刺突は全身の型
   * なので、そのまま流すと立ち上がってしまう。しゃがみ用のクリップが無いので、
   * 下は crouch_idle を流したまま上に刺突を重ねる。
   *
   * 倒れている相手を刺すのに要る (見下ろして刺す。sim/hitcheck.ts の
   * STAB_DOWN_PITCH)。立ち上がってしまうと、そもそも見下ろせない。
   */
  | 'crouch_stab'
  /**
   * 階段を上っている。**坂は含めない。**
   *
   * 段差を 1 段ずつ上がる動きで、走りの型のまま上がると足が段に埋まる。
   * 坂は連続して上がるので、走りの型のままで破綻しない。
   */
  | 'up_stair'
  /**
   * 階段を下りている。
   *
   * 上りと分ける。**同じ型を逆再生しても下りには見えない** — 下りは踏み外さない
   * ように体を落として着地を吸収する動きで、上りとは重心の運び方が違う。
   */
  | 'down_stair'
  | 'roll'
  /**
   * 高い所から落ちた着地。**膝を突いて堪える。**
   *
   * ただの着地 (jump_down) と分ける。damage.ts の落下ダメージが入る速さで
   * 落ちたときだけこちら — 削られたことが体でも分かる。
   *
   * **その場から動かない。** 受け身を取って転がる型だった頃は 3m 進んで
   * いたが、堪える型に差し替わったので移動しない。
   */
  | 'hard_land'
  /**
   * 麻酔で眠っている。
   *
   * 倒れている (death) とは別物。**体はそこに在り続け、30 秒で起きる。**
   * 見分けが付かないと、通りかかった人が「もう倒れている」と読んで素通りする。
   */
  | 'sleep'
  // 倒れるのは全身。怯みは上半身だけなので Locomotion には含めない
  // (脚まで止めると被弾のたびに 1.6 秒棒立ちになる)。
  | 'death'
  /**
   * 倒れる向き。**撃たれた側から見て、前か後ろか。**
   *
   *     death_front  背後から撃たれた → 前へ倒れる (うつ伏せ)
   *     death_back   正面から撃たれた → 後ろへ倒れる (仰向け)
   *
   * 向きを絵に出すのは、**倒れた人を見た側が「どこから撃たれたか」を読める**
   * ようにするため。味方が前のめりに倒れたなら、撃った相手はその先ではなく
   * 後ろに居る。
   *
   * 決めるのは撃たれた側 (位置と向きを持っているのがそこ)。姿勢として流れる
   * ので、他人の画面にもそのまま届く。
   */
  | 'death_front'
  | 'death_back'
  /**
   * 伏せたまま倒された。
   *
   * 立っている型で倒れると、**伏せていた体が一度立ち上がってから崩れる。**
   * 撃たれた瞬間に姿勢が飛ぶので、見ている側は何が起きたか読めない。
   */
  | 'prone_death'
  /** 伏せたまま後ろへ下がる。前進 (crawl_f) と対 */
  | 'crawl_b'
  // 敬礼。全身の型なので上下を分けない
  | 'salute'
  /**
   * クレイモアを構える / 置く。**全身の型**。
   *
   * かがんで置くので、上半身だけ切り出すと腰の向きが下半身と食い違う
   * (刺突と同じ理由)。しゃがむ動作なので、構えとしても crouch として扱う —
   * 置いている間は頭が下がって、見つかりにくい代わりに動けない。
   */
  | 'claymore_windup'
  | 'claymore_place'
  /**
   * 接続が切れて、体だけ残っている姿。
   *
   * 自分でこの状態になることは無い — **サーバーが書き込む**。切れた人の
   * 最後の位置を配り続けるときに、この姿勢に差し替える。
   */
  | 'away'
  // 爆風で倒れる / そこから立ち上がる。倒れている間も撃てるよう、
  // 下半身だけ倒れた姿勢のまま留める
  | 'sweep'
  | 'stand'
  /**
   * 伏せている。**しゃがみの下にもう一段。**
   *
   * 止まっている姿と這っている姿を分ける。ダンボールの sneak / sit と同じ理由で、
   * 進む型を止まったまま流すとその場で足踏みして見える。
   *
   * 這うのは**前だけ**。素材が前進の 1 本しかない — 横へ滑る体が前へ進む型を
   * していると確実に崩れるので、行けない向きは行けないままにしてある。
   */
  | 'prone_idle'
  | 'crawl_f'
  /**
   * 伏せに入る / 伏せから起き上がる。**どちらも全身の型。**
   *
   * 姿勢が繋がっていないと、立った姿から 1 フレームで腹這いになる。倒れる
   * (sweep) / 起き上がる (stand) と同じで、**間を見せることが代償**になる。
   *
   * 起き上がった先は**しゃがみ**。型がそこで終わるので、立ちへ戻すと
   * 型の終わりと姿勢が食い違う。
   */
  | 'prone_down'
  | 'prone_rise'
  /**
   * 吹き飛ばされて仰向けに倒れた所から、腹這いへ寝返る。
   *
   * 転ぶ型 (sweep) は**仰向けで終わる**ので、そのまま這う型へ渡すと 1 フレーム
   * で腹這いに裏返る。這い出すのに寝返る間を挟むのは、伏せに入るのに
   * prone_down を挟むのと同じ話。
   */
  | 'prone_turn'
  /**
   * ダンボールで走っていて敵にぶつかった。**箱が落ちて棒立ちになる。**
   *
   * 上下を分けない全身の型。倒れるのとは違って撃てないだけで立ってはいるが、
   * この間は動けない — 見つかった代償をここで払う。
   */
  | 'bump'
  // 落下は 3 分割。滞空時間がクリップ尺と一致しなくても破綻しない。
  | 'jump_up'
  | 'jump_loop'
  | 'jump_down'
  | `run_${MoveDirection}`
  | `crouch_${MoveDirection}`

/** 立ち / しゃがみ、それぞれの 8 方向の状態を引く */
export function locomotionFor(crouching: boolean, direction: MoveDirection): Locomotion {
  return crouching ? `crouch_${direction}` : `run_${direction}`
}
