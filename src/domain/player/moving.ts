/**
 * 動ける範囲。
 *
 * **乗れるか乗れないかは、遊びの話。** 段差をどれだけ跨げるかで通れる道が
 * 変わり、「その箱の上から撃てる」「その縁は登れないから回り込む」という
 * 判断が生まれる。押し戻しの計算そのもの (何回繰り返すか、どれだけ食い込みを
 * 許すか) は世界の側なので sim/space/collision.ts。
 *
 * 走る速さや跳ぶ高さも本来はここに来る数字だが、いまは
 * presentation/scene/actor/player.ts に置いたままになっている。
 */

/**
 * 足を乗せられる段差 (m)。
 *
 * 階段 1 段ぶん。これを超える縁は登れないので、回り込むか跳ぶことになる。
 * ステージを作る側もこの値に合わせて段を刻む (tools/export_stage.py)。
 */
export const STEP_UP = 0.25

/**
 * 立ち姿の全高 (m)。
 *
 * **くぐれるか、頭がぶつかるか。** 梁の下を通れるかどうかがこれで決まるので、
 * 段差と同じく遊びの数字。カプセルの寸法 (円柱 1.1 + 半球 0.35 × 2) から
 * 来ていて、presentation/scene/actor/soldier.ts がそれを組み立てている。
 *
 * ここに置くのは、**地形の側も同じ数字を要る**から。三角の網の上を歩くとき、
 * 頭がぶつかる高さを測るのに体の高さが要る (sim/space/meshworld.ts)。
 * 地形が人のファイルを読むのは向きが逆なので、共有の数字はこちらへ。
 */
export const PLAYER_HEIGHT = 1.8
